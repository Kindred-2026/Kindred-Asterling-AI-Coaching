// `pnpm verify` component "generate:check" — OpenAPI/Orval generated-client
// consistency WITHOUT rewriting developer files.
//
// Orval generation writes into `lib/api-client-react/src/generated` and
// `lib/api-zod/src/generated` with `clean: true`. This check instead runs the
// SAME committed `orval --config ./orval.config.ts` invocation from a
// sandboxed copy of the workspace tree (with `node_modules` symlinked back to
// the real store), then byte-compares the regenerated output against the
// tracked generated trees. Any added, removed or changed file fails the check,
// so a contract/generator mismatch is detected without ever mutating tracked
// files.
//
// The sandbox faithfully mirrors the real package context (working directory,
// tsconfigs, `.prettierrc.json`, mutator file, openapi contract), so the
// regenerated bytes are exactly what `pnpm --filter @workspace/api-spec run
// codegen` would produce. Both the sandbox output and a copy of the tracked
// trees are passed through the same neutral prettier pass before comparison,
// so prettier flavor differences cannot cause spurious diffs.

import { spawnSync } from "node:child_process";
import fsp from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { normalizeGenerated } from "./generated-normalize.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));

const GENERATED_TREES = [
  {
    name: "api-client-react",
    tracked: path.join(ROOT, "lib", "api-client-react", "src", "generated"),
  },
  {
    name: "api-zod",
    tracked: path.join(ROOT, "lib", "api-zod", "src", "generated"),
  },
];

// Minimal generator-input snapshot: only the files orval generation needs — the
// api-spec contract/config, the generated-client packages' hand-authored
// sources, and the root workspace/toolchain config. Secret/operational files
// (any .env*, SECRET_INVENTORY.md, deploy/, infrastructure/, artifacts/, docs/,
// frontend/, .github/, ...) are never copied into the sandbox.
const SNAPSHOT_DIRS = ["lib/api-spec", "lib/api-client-react", "lib/api-zod"];
const SNAPSHOT_FILES = [
  "package.json",
  "pnpm-workspace.yaml",
  "pnpm-lock.yaml",
  "tsconfig.json",
  "tsconfig.base.json",
  ".npmrc",
  ".prettierrc.json",
  ".prettierignore",
];

// Never copy into the snapshot: dependency stores (symlinked back), VCS
// metadata, build metadata, and any environment/secret file regardless of
// location.
function shouldCopy(source) {
  const base = path.basename(source);
  if (base === "node_modules" || base === ".git") return false;
  if (base.endsWith(".tsbuildinfo")) return false;
  if (base.startsWith(".env")) return false;
  return true;
}

export async function snapshotGeneratorInputs(root, harness) {
  for (const rel of SNAPSHOT_FILES) {
    const src = path.join(root, rel);
    if (await fsp.stat(src).catch(() => null)) {
      await fsp.cp(src, path.join(harness, rel), { recursive: true, filter: shouldCopy });
    }
  }
  for (const rel of SNAPSHOT_DIRS) {
    const src = path.join(root, rel);
    if (await fsp.stat(src).catch(() => null)) {
      await fsp.cp(src, path.join(harness, rel), { recursive: true, filter: shouldCopy });
    }
  }
}

async function snapshotDir(dir, { normalize = false } = {}) {
  const files = new Map();
  async function walk(abs, rel) {
    const entries = await fsp.readdir(abs, { withFileTypes: true });
    for (const entry of entries) {
      const childAbs = path.join(abs, entry.name);
      const childRel = rel ? `${rel}/${entry.name}` : entry.name;
      if (entry.isDirectory()) await walk(childAbs, childRel);
      else {
        const bytes = await fsp.readFile(childAbs);
        files.set(
          childRel,
          normalize ? Buffer.from(normalizeGenerated(bytes.toString("utf8")), "utf8") : bytes,
        );
      }
    }
  }
  if ((await fsp.stat(dir).catch(() => null)) === null) return files;
  await walk(dir, "");
  return files;
}

// Pure comparison for tests and reports. Returns { removed, added, changed }.
export function compareGeneratedTrees(base, candidate) {
  const removed = [];
  const added = [];
  const changed = [];
  for (const [rel, bytes] of base) {
    if (!candidate.has(rel)) removed.push(rel);
    else if (!bytes.equals(candidate.get(rel))) changed.push(rel);
  }
  for (const rel of candidate.keys()) {
    if (!base.has(rel)) added.push(rel);
  }
  return {
    removed: removed.sort(),
    added: added.sort(),
    changed: changed.sort(),
  };
}

function safeGenEnv(parent = process.env) {
  const kept = {};
  for (const key of ["PATH", "HOME", "TMPDIR", "TMP", "TERM", "LANG"]) {
    if (parent[key] !== undefined) kept[key] = parent[key];
  }
  return kept;
}

async function linkNodeModules(copyRoot, realRoot) {
  // Root node_modules plus every package node_modules under lib/, so pnpm-era
  // resolution from the sandbox hits the real store.
  await fsp.symlink(
    path.join(realRoot, "node_modules"),
    path.join(copyRoot, "node_modules"),
    "dir",
  );
  for (const entry of await fsp.readdir(path.join(realRoot, "lib"), {
    withFileTypes: true,
  })) {
    if (!entry.isDirectory()) continue;
    const destParent = path.join(copyRoot, "lib", entry.name);
    if (!(await fsp.stat(destParent).catch(() => null))) continue;
    const real = path.join(realRoot, "lib", entry.name, "node_modules");
    if (await fsp.stat(real).catch(() => null)) {
      await fsp.symlink(real, path.join(destParent, "node_modules"), "dir");
    }
  }
}

async function normalizeWithNeutralPrettier(root, targetDirs) {
  const neutral = path.join(root, "neutral-prettier.json");
  const emptyIgnore = path.join(root, "empty-ignore");
  await fsp.writeFile(neutral, "{}\n");
  await fsp.writeFile(emptyIgnore, "");
  for (const dir of targetDirs) {
    const r = spawnSync(
      "pnpm",
      [
        "exec",
        "prettier",
        "--config",
        neutral,
        "--ignore-path",
        emptyIgnore,
        "--write",
        path.join(dir, "**", "*.{ts,tsx,mjs,js}"),
      ],
      { cwd: ROOT, encoding: "utf8" },
    );
    if (r.status !== 0) {
      throw new Error(`prettier normalization failed for ${dir}: ${r.stderr || r.stdout}`);
    }
  }
}

export async function checkGeneratedDrift({
  root = ROOT,
  log = (message) => console.log(message),
  trees = GENERATED_TREES,
  runCommand = (args, options) => spawnSync(args[0], args.slice(1), options),
} = {}) {
  const harness = await fsp.mkdtemp(path.join(os.tmpdir(), "kindred-verify-gen-"));
  try {
    // Minimal sandbox copy of the generator inputs only. node_modules/.git and
    // secret/operational files are never copied; the stores are symlinked back
    // so resolution matches a real run.
    await snapshotGeneratorInputs(root, harness);
    await linkNodeModules(harness, root);

    const orval = runCommand(
      [
        path.join(root, "lib", "api-spec", "node_modules", ".bin", "orval"),
        "--config",
        "./orval.config.ts",
      ],
      {
        cwd: path.join(harness, "lib", "api-spec"),
        stdio: "inherit",
        env: safeGenEnv(process.env),
      },
    );
    if (orval.status !== 0) {
      throw new Error(`orval generation failed (exit ${orval.status ?? "signal"})`);
    }

    let anyDrift = false;
    for (const tree of trees) {
      const sandboxOut = path.join(harness, "lib", tree.name, "src", "generated");
      const tmpTracked = path.join(harness, "tracked", tree.name);
      await fsp.cp(tree.tracked, tmpTracked, { recursive: true });
      await normalizeWithNeutralPrettier(harness, [sandboxOut, tmpTracked]);

      const drift = compareGeneratedTrees(
        await snapshotDir(tmpTracked, { normalize: true }),
        await snapshotDir(sandboxOut, { normalize: true }),
      );
      const total = drift.added.length + drift.removed.length + drift.changed.length;
      if (total > 0) {
        anyDrift = true;
        const lines = [
          `generated-client drift for "${tree.name}":`,
          ...drift.added.map((f) => `  added     ${f}`),
          ...drift.removed.map((f) => `  removed   ${f}`),
          ...drift.changed.map((f) => `  changed   ${f}`),
        ];
        log(lines.join("\n"));
      } else {
        log(`[generate:check] ${tree.name}: generated output matches tracked files`);
      }
    }
    if (anyDrift) {
      log(
        "generate:check FAILED: run `pnpm --filter @workspace/api-spec run codegen` and commit the regenerated output.",
      );
      return { ok: false };
    }
    return { ok: true };
  } finally {
    await fsp.rm(harness, { recursive: true, force: true });
  }
}

async function main() {
  process.exitCode = (await checkGeneratedDrift()).ok ? 0 : 1;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main();
}
